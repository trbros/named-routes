import { open, realpath, stat } from 'node:fs/promises';
import { isAbsolute, relative, resolve, sep } from 'node:path';
import ts from 'named-routes-mcp-typescript';

const MAX_BYTES = 2 * 1024 * 1024;
const candidates = ['src/routes.generated.ts','src/routes.generated.mts','src/routes.generated.js','src/routes.generated.mjs','src/lib/routes.generated.ts','app/routes.generated.ts','app/utils/routes.ts','routes.generated.ts','routes.generated.js'];
const within = (root, file) => { const rel = relative(root,file); return rel !== '' && !isAbsolute(rel) && rel !== '..' && !rel.startsWith(`..${sep}`); };
function unwrap(node) {
  while (node && (ts.isParenthesizedExpression(node) || ts.isAsExpression(node) || ts.isSatisfiesExpression(node))) node=node.expression;
  return node;
}
function keyOf(name) {
  if (ts.isStringLiteral(name) || ts.isIdentifier(name)) return name.text;
  if (ts.isComputedPropertyName(name) && ts.isStringLiteral(name.expression)) return name.expression.text;
  throw new Error('Nonliteral route name in generated manifest.');
}
export function parseManifest(source, filename='routes.generated.ts') {
  if (!/^\/\/ Generated by @triooo\/(?:next-)?named-routes\. Do not edit\.(?:\r?\n|$)/.test(source)) throw new Error('Not a recognized Named Routes generated file.');
  const ast = ts.createSourceFile(filename,source,ts.ScriptTarget.Latest,true,filename.endsWith('.js')||filename.endsWith('.mjs') ? ts.ScriptKind.JS : ts.ScriptKind.TS);
  if (ast.parseDiagnostics.length) throw new Error('Generated manifest contains syntax errors.');
  const declarations = new Map();
  for (const s of ast.statements) {
    if (!ts.isVariableStatement(s) || !s.modifiers?.some(m=>m.kind===ts.SyntaxKind.ExportKeyword)) continue;
    for (const d of s.declarationList.declarations) if (ts.isIdentifier(d.name) && d.initializer) declarations.set(d.name.text, d.initializer);
  }
  const references = [...declarations.values()].filter(e=>ts.isCallExpression(e)&&ts.isIdentifier(e.expression)&&e.expression.text==='createRoutes'&&e.arguments[0]&&ts.isIdentifier(e.arguments[0])).map(e=>e.arguments[0].text);
  if (references.length!==1) throw new Error('Expected one generated createRoutes call with a named manifest.');
  const frozen = declarations.get(references[0]);
  if (!frozen || !ts.isCallExpression(frozen) || !ts.isPropertyAccessExpression(frozen.expression) || frozen.expression.expression.getText(ast)!=='Object' || frozen.expression.name.text!=='freeze' || frozen.arguments.length!==1) throw new Error('Expected a frozen literal manifest.');
  const literal=unwrap(frozen.arguments[0]);
  if (!literal || !ts.isObjectLiteralExpression(literal)) throw new Error('Manifest is not a literal object.');
  const entries=[]; const seen=new Set();
  for (const p of literal.properties) {
    if (!ts.isPropertyAssignment(p) || !ts.isStringLiteral(p.initializer) || !p.initializer.text.startsWith('/')) throw new Error('Nonliteral or invalid route pattern.');
    const name=keyOf(p.name);
    if (seen.has(name)) throw new Error('Duplicate route name.');
    seen.add(name); entries.push({name,pattern:p.initializer.text});
  }
  return entries.sort((a,b)=>a.name.localeCompare(b.name));
}
export async function loadManifest(root, selected) {
  if (!root) throw new Error('Route inspection is disabled. Start with --root <trusted-project> and optionally --manifest <relative-file>.');
  const base=await realpath(root);
  if (selected && (isAbsolute(selected) || !within(base, resolve(base, selected)))) throw new Error('Manifest must be a relative path within the configured root.');
  const available=[];
  for (const name of selected ? [selected] : candidates) {
    const target=resolve(base,name);
    let actual; try { actual=await realpath(target); } catch(e) { if (e.code==='ENOENT'&&!selected) continue; throw e; }
    if (!within(base,actual)) throw new Error('Manifest resolves outside the configured project.');
    if (!/\.(?:ts|mts|js|mjs)$/.test(actual)) throw new Error('Expected a generated TS/JS module.');
    available.push({name,actual});
  }
  if (available.length!==1) throw new Error(available.length ? 'Multiple manifests found; restart with --manifest <relative-file>.' : 'No generated manifest found. Generate it in the project, or specify --manifest.');
  const {name,actual}=available[0];
  const before=await stat(actual);
  if (!before.isFile() || before.size>MAX_BYTES) throw new Error('Manifest must be a regular file under 2 MiB.');
  const fd=await open(actual,'r');
  try {
    const st=await fd.stat();
    if (!st.isFile() || st.size>MAX_BYTES) throw new Error('Manifest must be a regular file under 2 MiB.');
    const buf=Buffer.alloc(MAX_BYTES+1); let size=0;
    while (size<buf.length) { const {bytesRead}=await fd.read(buf,size,buf.length-size,null); if (!bytesRead) break; size+=bytesRead; }
    if (size>MAX_BYTES) throw new Error('Manifest exceeds 2 MiB.');
    return { file:name, entries:parseManifest(buf.subarray(0,size).toString('utf8'),actual) };
  } finally { await fd.close(); }
}
