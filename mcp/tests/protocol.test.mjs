import test from 'node:test';
import assert from 'node:assert/strict';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
import { fileURLToPath } from 'node:url';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
for (const mode of ['dedicated', 'subcommand']) test(`real MCP stdio (${mode}): handshake, tools, resources, errors and inventory`, {timeout:30000}, async()=>{
  const root=await mkdtemp(join(tmpdir(),'named routes MCP '));
  const client=new Client({name:'named-routes-test',version:'1.0.0'});
  try {
    await writeFile(join(root,'routes.generated.ts'),'// Generated by @triooo/named-routes. Do not edit.\nexport const routes=Object.freeze({home:"/"} as const); export const route=createRoutes(routes,{});');
    const packageRoot=process.env.NAMED_ROUTES_MCP_TEST_PACKAGE ?? fileURLToPath(new URL('../../',import.meta.url));
    const entry=join(packageRoot,'bin',mode==='dedicated'?'named-routes-mcp.js':'named-routes.js');
    await client.connect(new StdioClientTransport({command:process.execPath,args:[entry,...(mode==='subcommand'?['mcp']:[]),'--root',root]}));
    const {tools}=await client.listTools(); assert.equal(tools.length,6);
    const result=await client.callTool({name:'list_routes',arguments:{}}); assert.equal(result.isError??false,false); assert.equal(JSON.parse(result.content[0].text).entries[0].name,'home');
    const error=await client.callTool({name:'get_route',arguments:{name:'missing'}}); assert.equal(error.isError,true);
    const doc=await client.callTool({name:'search_docs',arguments:{query:'astro'}});assert.equal(doc.isError??false,false);assert.ok(JSON.parse(doc.content[0].text).results.length);
    const {resources}=await client.listResources();assert.ok(resources.some(r=>r.uri==='named-routes://agent-contract'));
    const resource=await client.readResource({uri:'named-routes://agent-contract'});assert.ok(resource.contents[0].text.includes('route.url'));
  } finally { await client.close();await rm(root,{recursive:true,force:true}); }
});
