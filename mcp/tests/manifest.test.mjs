import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parseManifest, loadManifest } from '../src/manifest.mjs';
const header='// Generated by @triooo/named-routes. Do not edit.\n';
const fixture=header+`import {createRoutes} from '@triooo/named-routes';
export const inventory=Object.freeze({["users.$user"]:"/users/[user]", "about":"/about"} as const);
export const route=createRoutes(inventory,{});
throw new Error('Must never execute');`;
test('parse generated TS and custom manifest export without executing',()=>{
  assert.deepEqual(parseManifest(fixture),[{name:'about',pattern:'/about'},{name:'users.$user',pattern:'/users/[user]'}]);
});
test('parse generated JS, reject dynamic values, arbitrary files and duplicate names',()=>{
  const source=header+'export const routes=Object.freeze(/** @type {const} */ ({home:"/"})); export const route=createRoutes(routes,{});';
  assert.deepEqual(parseManifest(source,'routes.generated.js'),[{name:'home',pattern:'/'}]);
  assert.throws(()=>parseManifest(source.replace('"/"','evil()'),'routes.generated.js'),/Nonliteral/);
  assert.throws(()=>parseManifest(source.replace('home:"/"','home:"/",home:"/a"'),'routes.generated.js'),/Duplicate/);
  assert.throws(()=>parseManifest('export const routes={}'),/recognized/);
});
test('read only selected in-root generated file and reject ambiguous or external paths',async()=>{
  const base=await mkdtemp(join(tmpdir(),'named routes mcp '));
  const root=join(base,'project');
  try {
    await mkdir(join(root,'src'),{recursive:true});
    await writeFile(join(root,'src/routes.generated.ts'),fixture);
    assert.equal((await loadManifest(root)).entries.length,2);
    await writeFile(join(root,'routes.generated.ts'),fixture);
    await assert.rejects(loadManifest(root),/Multiple/);
    assert.equal((await loadManifest(root,'routes.generated.ts')).entries.length,2);
    await writeFile(join(base,'outside.ts'),fixture);
    await assert.rejects(loadManifest(root,'../outside.ts'),/relative path/);
    await assert.rejects(loadManifest(root,join(base,'outside.ts')), /relative path/);
    await assert.rejects(loadManifest(undefined),/disabled/);
    if(process.platform!=='win32') {
      await symlink(join(base,'outside.ts'),join(root,'linked.ts'));
      await assert.rejects(loadManifest(root,'linked.ts'),/outside/);
    }
  } finally { await rm(base,{recursive:true,force:true}); }
});
