import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdir, mkdtemp, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const exec = promisify(execFile);
const cli = fileURLToPath(new URL("../dist/cli.js", import.meta.url));
async function project(t, dependencies, files) {
	const root = await mkdtemp(join(tmpdir(), "named-doctor-"));
	t.after(() => rm(root, { recursive: true, force: true }));
	await writeFile(
		join(root, "package.json"),
		JSON.stringify({ type: "module", dependencies }),
	);
	for (const [file, content] of Object.entries(files)) {
		await mkdir(join(root, file, ".."), { recursive: true });
		await writeFile(join(root, file), content);
	}
	return root;
}
async function doctor(root, ...args) {
	try {
		const { stdout } = await exec(
			process.execPath,
			[cli, "doctor", "--root", root, ...args],
			{ env: { ...process.env, NO_COLOR: "1" } },
		);
		return { code: 0, stdout };
	} catch (caught) {
		return { code: caught.code, stdout: caught.stdout };
	}
}
const ids = (report) =>
	report.diagnostics.map((item) => `${item.level}:${item.id}`);
async function listing(root) {
	const entries = [];
	const walk = async (directory) => {
		for (const child of await readdir(directory, { withFileTypes: true })) {
			entries.push(join(directory, child.name));
			if (child.isDirectory()) await walk(join(directory, child.name));
		}
	};
	await walk(root);
	return entries.sort();
}

test("a healthy Next.js project passes; doctor never writes", async (t) => {
	const root = await project(
		t,
		{ next: "16" },
		{
			"app/page.tsx": "",
			"app/users/[id]/page.tsx": "",
			"next.config.mjs":
				'import { withNamedRoutes } from "@triooo/named-routes/next";\nexport default withNamedRoutes({});\n',
		},
	);
	const before = await listing(root);
	const { code, stdout } = await doctor(root, "--json");
	assert.equal(code, 0);
	const report = JSON.parse(stdout);
	assert.equal(report.framework, "next");
	assert.deepEqual(
		report.routes.map((item) => item.name),
		["home", "users.$id"],
	);
	assert.ok(ids(report).includes("info:integration.next"));
	assert.ok(
		ids(report).includes("warning:output.missing"),
		"missing module is a warning",
	);
	assert.deepEqual(
		await listing(root),
		before,
		"doctor must not create or change files",
	);
	// Warnings fail only with --strict.
	assert.equal((await doctor(root, "--strict")).code, 1);
	const human = await doctor(root);
	assert.match(human.stdout, /^named-routes doctor · /);
	assert.match(
		human.stdout,
		/^warning {2}Generated module not found: src\/routes\.generated\.ts$/m,
	);
	// biome-ignore lint/suspicious/noControlCharactersInRegex: asserts that no ANSI escape codes are printed
	assert.doesNotMatch(human.stdout, /\u001b\[/, "no ANSI codes without a TTY");
	assert.match(human.stdout, /0 error\(s\), 1 warning\(s\)/);
});

test("conflicts are errors with files and a fix; stale modules are warnings", async (t) => {
	const root = await project(
		t,
		{ next: "16" },
		{ "app/(a)/about/page.tsx": "", "app/(b)/about/page.tsx": "" },
	);
	const { code, stdout } = await doctor(root, "--json");
	assert.equal(code, 1);
	const failure = JSON.parse(stdout).diagnostics.find(
		(item) => item.id === "discovery.failed",
	);
	assert.deepEqual(failure.details.files, [
		"app/(a)/about/page.tsx",
		"app/(b)/about/page.tsx",
	]);
	assert.equal(failure.details.code, "GENERATION_ERROR");
	assert.match(failure.details.hint, /same URL/);

	const stale = await project(
		t,
		{ next: "16" },
		{
			"app/page.tsx": "",
			"src/routes.generated.ts":
				"// Generated by @triooo/named-routes. Do not edit.\nexport {};\n",
			"next.config.mjs": "export default withNamedRoutes({})",
		},
	);
	const report = JSON.parse((await doctor(stale, "--json")).stdout);
	assert.ok(ids(report).includes("warning:output.stale"));
});

test('configuration errors, typedRoutes with hrefs: "string" and the framework fallback', async (t) => {
	const typo = await project(
		t,
		{ next: "16" },
		{ "app/page.tsx": "", "named-routes.config.json": '{"ouput":"x.ts"}' },
	);
	const report = JSON.parse((await doctor(typo, "--json")).stdout);
	const config = report.diagnostics.find(
		(item) => item.id === "discovery.failed" || item.id === "config.load",
	);
	assert.equal(config.level, "error");
	assert.equal(config.details.hint, 'Did you mean "output"?');

	const typed = await project(
		t,
		{ next: "16" },
		{
			"app/page.tsx": "",
			"next.config.ts":
				'export default withNamedRoutes({ typedRoutes: true }, { hrefs: "string" });',
		},
	);
	assert.ok(
		ids(JSON.parse((await doctor(typed, "--json")).stdout)).includes(
			"warning:typescript.typed-routes",
		),
	);
	const fixed = await project(
		t,
		{ next: "16" },
		{
			"app/page.tsx": "",
			"next.config.ts":
				"export default withNamedRoutes({ typedRoutes: true });",
		},
	);
	assert.ok(
		!ids(JSON.parse((await doctor(fixed, "--json")).stdout)).includes(
			"warning:typescript.typed-routes",
		),
	);

	const unknown = await project(t, {}, { "app/page.tsx": "" });
	assert.ok(
		ids(JSON.parse((await doctor(unknown, "--json")).stdout)).includes(
			"warning:framework.fallback",
		),
	);
});

test("code-declared routes the scanner cannot see are reported (text checks)", async (t) => {
	const nuxt = await project(
		t,
		{ nuxt: "4" },
		{
			"app/pages/index.vue": "",
			"app/pages/legacy.vue":
				'<script setup>\ndefinePageMeta({\n  path: "/old-url",\n})\n</script>',
			"nuxt.config.ts":
				'export default defineNuxtConfig({ vite: { plugins: [namedRoutes({ output: "app/routes.generated.ts" })] } })',
		},
	);
	const nuxtReport = JSON.parse((await doctor(nuxt, "--json")).stdout);
	const declared = nuxtReport.diagnostics.find(
		(item) => item.id === "declarations.nuxt-path",
	);
	assert.equal(declared.details.file, "app/pages/legacy.vue");
	assert.ok(ids(nuxtReport).includes("info:integration.inline-options"));
	assert.ok(
		ids(nuxtReport).includes("info:output.missing"),
		"inline output: not knowable, so info",
	);

	const reactRouter = await project(
		t,
		{ "@react-router/dev": "8" },
		{
			"app/routes/_index.tsx": "",
			"app/routes.ts":
				'import { route, index } from "@react-router/dev/routes";\nexport default [index("home.tsx"), route("about", "about.tsx")];',
			"vite.config.ts": "export default { plugins: [] }",
		},
	);
	const rrReport = JSON.parse((await doctor(reactRouter, "--json")).stdout);
	assert.ok(ids(rrReport).includes("warning:declarations.react-router-config"));
	assert.ok(ids(rrReport).includes("warning:integration.vite"));
});
