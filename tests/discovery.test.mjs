async function project(t, dependencies, files) {
	const root = await mkdtemp(join(tmpdir(), "named-discovery-"));
	t.after(() => rm(root, { recursive: true, force: true }));
	await writeFile(
		join(root, "package.json"),
		JSON.stringify({ name: "fixture", private: true, dependencies }),
	);
	for (const [file, content] of Object.entries(files)) {
		await mkdir(dirname(join(root, file)), { recursive: true });
		await writeFile(join(root, file), content);
	}
	return root;
}

test("path syntaxes convert to canonical patterns", () => {
	const vue = {
		"/": "/",
		"/users/:id": "/users/[id]",
		"/users/:id()": "/users/[id]",
		"/users/:id(\\d+)": "/users/[id]",
		"/:lang?/about": "/[[lang]]/about",
		"/docs/:path(.*)": "/docs/[[...path]]",
		"/docs/:slug(.*)*": "/docs/[[...slug]]",
		"/files/:parts+": "/files/[...parts]",
		"/v:major-:minor": "/v[major]-[minor]",
		"/a\\:b": "/a:b",
	};
	for (const [input, output] of Object.entries(vue))
		assert.equal(vueRouterPathToPattern(input), output, input);
	assert.throws(() => vueRouterPathToPattern("/v:major?-x"), {
		code: "GENERATION_ERROR",
	});
	const react = {
		"": "/",
		"users/:id": "/users/[id]",
		":lang?/about": "/[[lang]]/about",
		"docs/*": "/docs/[[...splat]]",
	};
	for (const [input, output] of Object.entries(react))
		assert.equal(reactRouterPathToPattern(input), output, input);
	assert.throws(() => reactRouterPathToPattern("en?/about"), {
		code: "GENERATION_ERROR",
	});
	const tanstack = {
		"/": "/",
		"/posts/$postId": "/posts/[postId]",
		"/docs/$": "/docs/[[..._splat]]",
		"/{-$lang}/about": "/[[lang]]/about",
		"/post-{$id}.json": "/post-[id].json",
	};
	for (const [input, output] of Object.entries(tanstack))
		assert.equal(tanstackPathToPattern(input), output, input);
});

