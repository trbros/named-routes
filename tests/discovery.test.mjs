test("Vue Router 5: typed-router.d.ts is the route table, including definePage paths", async (t) => {
	const root = await project(
		t,
		{ "vue-router": "5" },
		{
			"src/pages/index.vue": "",
			"src/pages/about.vue":
				"<script setup>definePage({ path: '/sobre' })</script>",
			"src/pages/users/_parent.vue": "",
			"src/pages/users/[id].vue": "",
		},
	);
	// Before Vue Router has run: the files, with the reason.
	const before = await discoverRoutes({ root });
	assert.equal(before.discovery.used, "files");
	assert.match(before.discovery.fallback, /typed-router\.d\.ts not found/);
	assert.deepEqual(before.routes, {
		about: "/about",
		home: "/",
		"users.$id": "/users/[id]",
	});
	await writeFile(join(root, "typed-router.d.ts"), typedRouterDts);
	const after = await discoverRoutes({ root });
	assert.deepEqual(after.discovery, {
		requested: "framework",
		used: "framework",
		artifact: "typed-router.d.ts",
		inputs: [join(root, "typed-router.d.ts")],
	});
	assert.deepEqual(after.routes, {
		home: "/",
		sobre: "/sobre",
		"users.$id": "/users/[id]",
	});
	// The leaf page, not its _parent layout, owns the route.
	assert.equal(
		after.entries.find((entry) => entry.name === "users.$id").file,
		"src/pages/users/[id].vue",
	);
	assert.equal(
		after.entries.find((entry) => entry.name === "sobre").file,
		"src/pages/about.vue",
	);
	// 1.x behavior on request.
	const files = await discoverRoutes({ root, discovery: "files" });
	assert.deepEqual(files.routes, before.routes);
	assert.equal(files.discovery.used, "files");
	assert.equal(files.discovery.fallback, undefined);
	// exclude still applies to framework routes.
	const excluded = await discoverRoutes({
		root,
		exclude: ["src/pages/about.vue"],
	});
	assert.equal(excluded.routes.sobre, undefined);
	await assert.rejects(discoverRoutes({ root, discovery: "both" }), {
		code: "INVALID_CONFIG",
	});
	// A user file with that name is not mistaken for the framework's.
	await writeFile(join(root, "typed-router.d.ts"), "export {}");
	const foreign = await discoverRoutes({ root });
	assert.match(foreign.discovery.fallback, /not generated by vue-router/);
});

