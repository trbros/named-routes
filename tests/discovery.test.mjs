test("Nuxt module: pages:resolved writes the module and the CLI snapshot", async (t) => {
	const root = await project(t, { nuxt: "4" }, { "app/pages/index.vue": "" });
	const hooks = new Map();
	const nuxt = {
		options: {
			rootDir: root,
			buildDir: join(root, ".nuxt"),
			dev: false,
			// nuxt.config `namedRoutes: {...}`; inline module options win.
			namedRoutes: { output: "elsewhere.ts", exportNames: { route: "url" } },
		},
		hook: (name, listener) => hooks.set(name, listener),
	};
	const meta = await namedRoutesNuxt.getMeta();
	assert.equal(meta.configKey, "namedRoutes");
	await namedRoutesNuxt({ output: "app/routes.generated.ts" }, nuxt);
	await hooks.get("pages:resolved")(withRoot(nuxtPages, root));
	const module = await readFile(join(root, "app/routes.generated.ts"), "utf8");
	assert.match(module, /\["sobre"\]: "\/sobre"/);
	assert.match(module, /\["a-propos"\]: "\/a-propos"/);
	assert.match(module, /\["added-by-module"\]: "\/added-by-module"/);
	assert.match(module, /export const url = /);
	// The CLI reads the same table from .nuxt (written by nuxt prepare/dev/build).
	await writeFile(
		join(root, "named-routes.config.json"),
		JSON.stringify({
			output: "app/routes.generated.ts",
			exportNames: { route: "url" },
		}),
	);
	const { stdout } = await exec(process.execPath, [
		cli,
		"check",
		"--root",
		root,
	]);
	assert.match(
		stdout,
		/Up to date: .* from \.nuxt\/named-routes\/pages\.json\)/,
	);
	const listed = JSON.parse(
		(await exec(process.execPath, [cli, "list", "--root", root])).stdout,
	);
	assert.ok(listed.some((entry) => entry.path === "/sobre"));
	// Builds fail on generation errors; dev keeps running.
	await assert.rejects(
		hooks.get("pages:resolved")([{ path: "/a/:x?-:y", name: "bad" }]),
		{ code: "GENERATION_ERROR" },
	);
	const errors = [];
	const original = console.error;
	console.error = (message) => errors.push(message);
	t.after(() => (console.error = original));
	nuxt.options.dev = true;
	await hooks
		.get("pages:resolved")([
			{ path: "/b", name: "b" },
			{ path: "/b", name: "c" },
		])
		.catch(() => {});
	await hooks.get("pages:resolved")(withRoot(nuxtPages, root));
	assert.equal(errors.length, 0);
});

test("Vite plugin regenerates when the framework rewrites its route table", async (t) => {
	const root = await project(
		t,
		{ "vue-router": "5" },
		{ "src/pages/index.vue": "", "typed-router.d.ts": typedRouterDts },
	);
	const plugin = namedRoutes({ root });
	await plugin.buildStart.call({});
	let listener;
	plugin.configureServer({
		watcher: { on: (_event, callback) => (listener = callback) },
	});
	const output = join(root, "src/routes.generated.ts");
	assert.match(await readFile(output, "utf8"), /\["sobre"\]/);
	await writeFile(
		join(root, "typed-router.d.ts"),
		typedRouterDts.replace("'/sobre'", "'/acerca'"),
	);
	listener("change", join(root, "typed-router.d.ts"));
	for (let i = 0; i < 50; i++) {
		if ((await readFile(output, "utf8")).includes("acerca")) break;
		await new Promise((done) => setTimeout(done, 20));
	}
	assert.match(await readFile(output, "utf8"), /\["acerca"\]/);
});

